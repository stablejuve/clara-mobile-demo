const DICTS: Record<Lang, Record<Key, string>> = { en, es };
let lang: Lang = "en";
export const getLang = (): Lang => lang;
export const setLangValue = (l: Lang): void => { lang = l; };

export function tr(key: Key, vars?: Record<string, string | number>): string {
  const s = DICTS[lang][key];
  return vars ? s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? "")) : s;
}

/** Nombre visible de un concepto de beneficio: si es una clave de copy la traduce; si no, lo deja tal cual. */
export const conceptLabel = (concept: string): string => (concept in en ? tr(concept as Key) : concept);

const group = (cents: number) => (Math.abs(cents) / 100).toLocaleString("en-US", { minimumFractionDigits: 2, maximumFractionDigits: 2 });
/** «$1,234.56» (o «$100» con `short` cuando no hay centavos). */
export const usd = (cents: number, short = false): string => `${cents < 0 ? "−" : ""}$${short && cents % 100 === 0 ? (Math.abs(cents) / 100).toLocaleString("en-US") : group(cents)}`;
/** «COP 117,325»: pesos colombianos, sin centavos. */
export const cop = (cents: number): string => `COP ${Math.round(cents / 100).toLocaleString("en-US")}`;
